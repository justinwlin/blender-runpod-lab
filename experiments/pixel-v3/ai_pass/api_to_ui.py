"""Convert a ComfyUI API-format workflow to UI-format JSON (the kind the editor saves), using a saved /object_info dump.
python api_to_ui.py <object_info.json> <workflow.api.json> <out.ui.json>
NOTE: generated by this script, not exported from the ComfyUI editor. The API JSON is what was actually run (and the editor
can also open API JSON directly by drag and drop)."""
import json, sys
info = json.load(open(sys.argv[1])); api = json.load(open(sys.argv[2]))
WIDGET = {'INT', 'FLOAT', 'STRING', 'BOOLEAN', 'COMBO'}
ids = {k: i + 1 for i, k in enumerate(api)}; nodes = {}; links = []; depth = {}
def d_of(k):
    if k not in depth:
        ins = [v[0] for v in api[k]['inputs'].values() if isinstance(v, list) and len(v) == 2 and v[0] in api]
        depth[k] = 1 + max([d_of(i) for i in ins], default=-1)
    return depth[k]
out_links = {}
for k, n in api.items():
    d = info[n['class_type']]; spec = list(d['input'].get('required', {}).items()) + list(d['input'].get('optional', {}).items())
    inputs, widgets = [], ({} if n['class_type'].startswith('VHS_') else [])
    def addw(name, val):
        if isinstance(widgets, dict): widgets[name] = val
        else: widgets.append(val)
    for name, sp in spec:
        t = sp[0]; extra = sp[1] if len(sp) > 1 and isinstance(sp[1], dict) else {}
        is_w = isinstance(t, list) or t in WIDGET; tname = 'COMBO' if isinstance(t, list) else t
        dflt = extra.get('default', (t[0] if isinstance(t, list) and t else (extra.get('options') or [None])[0]))
        v = n['inputs'].get(name)
        if isinstance(v, list) and len(v) == 2 and v[0] in api:
            lid = len(links) + 1; src = api[v[0]]; st = info[src['class_type']]['output'][v[1]]
            links.append([lid, ids[v[0]], v[1], ids[k], len(inputs), st]); out_links.setdefault((v[0], v[1]), []).append(lid)
            e = {'name': name, 'type': tname, 'link': lid}
            if is_w: e['widget'] = {'name': name}; addw(name, dflt)
            inputs.append(e)
        elif is_w:
            addw(name, dflt if v is None else v)
            if extra.get('control_after_generate'): addw('control_after_generate', 'fixed')
        else: inputs.append({'name': name, 'type': tname, 'link': None})
    nodes[k] = {'id': ids[k], 'type': n['class_type'], 'inputs': inputs, 'widgets_values': widgets, 'title': f"{k} ({n['class_type']})"}
cols = {}
for k in api:
    c = d_of(k); row = cols.get(c, 0); cols[c] = row + 1
    d = info[api[k]['class_type']]; names = d.get('output_name', d['output'])
    nodes[k].update(pos=[60 + c * 460, 60 + row * 330], size=[400, 260], flags={}, order=ids[k] - 1, mode=0,
                    outputs=[{'name': names[i], 'type': t, 'links': out_links.get((k, i), []), 'slot_index': i} for i, t in enumerate(d['output'])],
                    properties={'Node name for S&R': api[k]['class_type']})
json.dump({'last_node_id': len(nodes), 'last_link_id': len(links), 'nodes': list(nodes.values()), 'links': links, 'groups': [], 'config': {}, 'extra': {}, 'version': 0.4},
          open(sys.argv[3], 'w'), indent=1, ensure_ascii=False)
print('ui json:', sys.argv[3], len(nodes), 'nodes', len(links), 'links')
